CREATE TABLE IF NOT EXISTS geoportal.datasets_grav_anom
(
    dataset_id bigint NOT NULL GENERATED ALWAYS AS IDENTITY ( INCREMENT 1 START 1 ),
    dataset_name text NOT NULL,
    acc_id bigint NOT NULL,
    dataset_level smallint NOT NULL,
    dataset_anom_type text NOT NULL,
    metadata_path text,
    created_at timestamp with time zone NOT NULL DEFAULT NOW(),
    geom geometry(MultiPolygon, 4326) NOT NULL,
    PRIMARY KEY (dataset_id)
);

CREATE TABLE IF NOT EXISTS geoportal.point_grav_anom
(
    point_id bigint NOT NULL GENERATED ALWAYS AS IDENTITY ( INCREMENT 1 START 1 ),
    dataset_id bigint NOT NULL,
    point_value numeric(8, 3) NOT NULL,
    point_obs_type text NOT NULL,
    geom geometry(Point, 4326) NOT NULL,
    PRIMARY KEY (point_id)
);

CREATE TABLE IF NOT EXISTS geoportal.raster_grav_anom
(
    raster_id bigint NOT NULL GENERATED ALWAYS AS IDENTITY ( INCREMENT 1 START 1 ),
    dataset_id bigint NOT NULL,
    raster_resolution_deg real NOT NULL,
    rast raster NOT NULL,
    PRIMARY KEY (raster_id)
);

CREATE TABLE IF NOT EXISTS geoportal.proposed_data
(
    propose_id bigint NOT NULL GENERATED ALWAYS AS IDENTITY ( INCREMENT 1 START 1 ),
    acc_id bigint NOT NULL,
    data_path text NOT NULL,
    metadata_path text NOT NULL,
    propose_status character varying(1) NOT NULL DEFAULT 'P',
    CHECK (propose_status IN ('P','A','R')),
    proposed_at timestamp with time zone NOT NULL DEFAULT NOW(),
    reviewed_at timestamp with time zone,
    PRIMARY KEY (propose_id)
);

-- Spatial indexes
CREATE INDEX idx_datasets_grav_geom    ON geoportal.datasets_grav_anom USING GIST (geom);
CREATE INDEX idx_point_grav_geom       ON geoportal.point_grav_anom    USING GIST (geom);
CREATE INDEX idx_raster_rast_hull      ON geoportal.raster_grav_anom   USING GIST (ST_ConvexHull(rast));

-- Other indexes
CREATE INDEX idx_accounts_subs_id      ON geoportal.accounts(subs_id);
CREATE INDEX idx_accounts_org_id       ON geoportal.accounts(org_id);
CREATE INDEX idx_point_dataset         ON geoportal.point_grav_anom(dataset_id);
CREATE INDEX idx_raster_dataset        ON geoportal.raster_grav_anom(dataset_id);
CREATE INDEX idx_datasets_grav_anom_acc_id ON geoportal.datasets_grav_anom(acc_id);
CREATE INDEX idx_subscription_status   ON geoportal.subscriptions(payment_status);
CREATE INDEX idx_subscription_created_at ON geoportal.subscriptions(created_at);
CREATE INDEX idx_subscriptions_tier_id ON geoportal.subscriptions(tier_id);
CREATE INDEX idx_proposed_status       ON geoportal.proposed_data(propose_status);
CREATE INDEX idx_proposed_at           ON geoportal.proposed_data(proposed_at);
CREATE INDEX idx_proposed_data_acc_id  ON geoportal.proposed_data(acc_id);

-- Foreign keys
ALTER TABLE geoportal.accounts      ADD FOREIGN KEY (org_id)     REFERENCES geoportal.organizations(org_id)        ON UPDATE NO ACTION ON DELETE NO ACTION NOT VALID;
ALTER TABLE geoportal.accounts      ADD FOREIGN KEY (subs_id)    REFERENCES geoportal.subscriptions(subs_id)       ON UPDATE NO ACTION ON DELETE CASCADE   NOT VALID;
ALTER TABLE geoportal.subscriptions ADD FOREIGN KEY (tier_id)    REFERENCES geoportal.subscriptions_tier(tier_id)  ON UPDATE NO ACTION ON DELETE NO ACTION NOT VALID;
ALTER TABLE geoportal.organizations ADD FOREIGN KEY (subs_id)    REFERENCES geoportal.subscriptions(subs_id)       ON UPDATE NO ACTION ON DELETE CASCADE   NOT VALID;
ALTER TABLE geoportal.raster_grav_anom  ADD FOREIGN KEY (dataset_id) REFERENCES geoportal.datasets_grav_anom(dataset_id) ON UPDATE NO ACTION ON DELETE CASCADE NOT VALID;
ALTER TABLE geoportal.point_grav_anom   ADD FOREIGN KEY (dataset_id) REFERENCES geoportal.datasets_grav_anom(dataset_id) ON UPDATE NO ACTION ON DELETE CASCADE NOT VALID;
ALTER TABLE geoportal.datasets_grav_anom ADD FOREIGN KEY (acc_id)    REFERENCES geoportal.accounts(acc_id)         ON UPDATE NO ACTION ON DELETE CASCADE   NOT VALID;
ALTER TABLE geoportal.proposed_data      ADD FOREIGN KEY (acc_id)    REFERENCES geoportal.accounts(acc_id)         ON UPDATE NO ACTION ON DELETE NO ACTION NOT VALID;

COMMIT;
