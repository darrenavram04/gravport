CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS postgis_raster;

DROP SCHEMA IF EXISTS geoportal CASCADE;
CREATE SCHEMA geoportal;

BEGIN;

CREATE TABLE IF NOT EXISTS geoportal.accounts
(
    acc_id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 ),
    subs_id bigint,
    org_id bigint,
    acc_name character varying(20) NOT NULL,
    acc_email character varying(255) NOT NULL UNIQUE,
    acc_password text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT NOW(),
    is_admin boolean NOT NULL DEFAULT false,
    is_logged_in boolean NOT NULL DEFAULT false,
    PRIMARY KEY (acc_id)
);

CREATE TABLE IF NOT EXISTS geoportal.organizations
(
    org_id bigint NOT NULL GENERATED ALWAYS AS IDENTITY ( INCREMENT 1 START 1 ),
    subs_id bigint,
    org_name text NOT NULL,
    org_email character varying(255) NOT NULL UNIQUE,
    PRIMARY KEY (org_id)
);

CREATE TABLE IF NOT EXISTS geoportal.subscriptions
(
    subs_id bigint NOT NULL GENERATED ALWAYS AS IDENTITY ( INCREMENT 1 START 1 ),
    tier_id smallint NOT NULL,
    midtrans_order_id text NOT NULL,
    payment_status character varying(1) NOT NULL DEFAULT 'P',
    CHECK (payment_status IN ('P','S','E')),
    payment_cycle character varying(1) NOT NULL,
    CHECK (payment_cycle IN ('M','A')),
    remaining_download_byte bigint NOT NULL,
    total_acc smallint NOT NULL DEFAULT 1,
    created_at timestamp with time zone NOT NULL DEFAULT NOW(),
    paid_at timestamp with time zone,
    end_at date,
    PRIMARY KEY (subs_id),
    UNIQUE (midtrans_order_id)
);

CREATE TABLE IF NOT EXISTS geoportal.subscriptions_tier
(
    tier_id smallint NOT NULL,
    tier_name text NOT NULL,
    price_monthly integer NOT NULL,
    price_annualy integer NOT NULL,
    max_acc smallint NOT NULL,
    download_quota_byte bigint,
    PRIMARY KEY (tier_id)
);

